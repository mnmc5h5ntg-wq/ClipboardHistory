def main():
    problems = []
    for path, old, new, times in EDITS:
        text = read(path)
        found = text.count(old)
        if found != times:
            problems.append("EDIT 命中 %d 次（期望 %d）：%s :: %s" % (found, times, path, old[:60]))
            continue
        write(path, text.replace(old, new))
        print("EDIT   %-34s %s" % (path, old[:56].replace("\n", " ")))
    for path, anchor, text in INSERT_BEFORE:
        source = read(path)
        found = source.count(anchor)
        if found != 1:
            problems.append("BEFORE 命中 %d 次（期望 1）：%s :: %s" % (found, path, anchor[:60]))
            continue
        write(path, source.replace(anchor, text + anchor, 1))
        print("BEFORE %-34s %s" % (path, anchor[:56].replace("\n", " ")))
    for path, text in APPENDS:
        write(path, read(path).rstrip("\n") + "\n" + text)
        print("APPEND %-34s +%d 行" % (path, text.count("\n")))
    if problems:
        print("\n=== 没改的（命中数不对，整条跳过）===")
        for line in problems:
            print("  " + line)
        return 1
    print("\n全部命中恰好一次。")
    return 0


