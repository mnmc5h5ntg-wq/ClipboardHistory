def main():
    failed = 0
    for path, old, new in EDITS:
        text = read(path)
        hits = text.count(old)
        if hits != 1:
            print("SKIP %s 锚点命中 %d 次（要恰好 1 次）：%r" % (path, hits, old[:60]))
            failed += 1
            continue
        write(path, text.replace(old, new, 1))
        print("EDIT %s ← %r" % (path, old[:52]))
    for path, text in APPENDS:
        write(path, read(path) + text)
        print("APPEND %s (+%d 字)" % (path, len(text)))
    print("失败=%d" % failed)
